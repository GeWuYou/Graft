package projection

import (
	"bytes"
	"fmt"
	"strings"
)

type renderGroup struct {
	kind        Kind
	constant    string
	typeName    string
	descriptors []Entry
}

var platformRenderGroups = []renderGroup{
	{kind: KindAuthScheme, constant: "AUTH_SCHEME", typeName: "AuthScheme"},
	{kind: KindErrorCode, constant: "ERROR_CODE", typeName: "ErrorCode"},
	{kind: KindHTTPHeader, constant: "HTTP_HEADER", typeName: "HttpHeader"},
	{kind: KindMessageKey, constant: "MESSAGE_KEY", typeName: "MessageKey"},
}

// RenderTypeScript 渲染稳定、可重建的 web 平台契约派生产物。
func RenderTypeScript(entries []Entry) ([]byte, error) {
	if err := Validate(entries); err != nil {
		return nil, err
	}

	visible := webEntries(entries)
	groups := make([]renderGroup, len(platformRenderGroups))
	copy(groups, platformRenderGroups)
	for _, entry := range visible {
		for index := range groups {
			if groups[index].kind == entry.Kind {
				groups[index].descriptors = append(groups[index].descriptors, entry)
				break
			}
		}
	}

	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by contractprojection; DO NOT EDIT.\n")
	buffer.WriteString("// Source: server/internal/contract/projection.Registry.\n\n")
	for _, group := range groups {
		if len(group.descriptors) == 0 {
			continue
		}
		_, _ = fmt.Fprintf(&buffer, "export const %s = {\n", group.constant)
		for _, entry := range group.descriptors {
			_, _ = fmt.Fprintf(&buffer, "  %s: %s,\n", entry.Name, typeScriptString(entry.Value.String()))
		}
		buffer.WriteString("} as const;\n\n")
		_, _ = fmt.Fprintf(&buffer, "export type %s = (typeof %s)[keyof typeof %s];\n\n", group.typeName, group.constant, group.constant)
	}
	return []byte(strings.TrimRight(buffer.String(), "\n") + "\n"), nil
}

func typeScriptString(value string) string {
	escaped := strings.ReplaceAll(value, "\\", "\\\\")
	escaped = strings.ReplaceAll(escaped, "'", "\\'")
	escaped = strings.ReplaceAll(escaped, "\n", "\\n")
	escaped = strings.ReplaceAll(escaped, "\r", "\\r")
	return "'" + escaped + "'"
}
