package projection

import (
	"bytes"
	"fmt"
	"strings"
)

const maxInlineTypeAliasLength = 120

type renderGroup struct {
	kind        Kind
	constant    string
	typeName    string
	descriptors []Entry
}

var defaultRenderGroups = []renderGroup{
	{kind: KindAuthScheme, constant: "AUTH_SCHEME", typeName: "AuthScheme"},
	{kind: KindErrorCode, constant: "ERROR_CODE", typeName: "ErrorCode"},
	{kind: KindHTTPHeader, constant: "HTTP_HEADER", typeName: "HttpHeader"},
	{kind: KindMessageKey, constant: "MESSAGE_KEY", typeName: "MessageKey"},
	{kind: KindPermissionCode, constant: "PERMISSION_CODE", typeName: "PermissionCode"},
	{kind: KindRealtimeTopic, constant: "REALTIME_TOPIC", typeName: "RealtimeTopic"},
	{kind: KindDockerImageRemoveErrorCode, constant: "DOCKER_IMAGE_REMOVE_ERROR_CODE", typeName: "DockerImageRemoveErrorCode"},
}

// RenderTypeScript 渲染稳定、可重建的 web contract 派生产物。
func RenderTypeScript(entries []Entry) ([]byte, error) {
	return renderTypeScript(entries, defaultRenderGroups)
}

// RenderTarget 根据 target 自己声明的导出 metadata 渲染 web 派生产物。
func RenderTarget(target Target) ([]byte, error) {
	groups := defaultRenderGroups
	if len(target.Groups) > 0 {
		groups = make([]renderGroup, len(target.Groups))
		for index, group := range target.Groups {
			groups[index] = renderGroup{kind: group.Kind, constant: group.Constant, typeName: group.TypeName}
		}
	}
	return renderTypeScript(target.Entries, groups)
}

func renderTypeScript(entries []Entry, renderGroups []renderGroup) ([]byte, error) {
	if err := Validate(entries); err != nil {
		return nil, err
	}

	visible := webEntries(entries)
	groups := make([]renderGroup, len(renderGroups))
	copy(groups, renderGroups)
	for _, entry := range visible {
		for index := range groups {
			if groups[index].kind == entry.Kind {
				groups[index].descriptors = append(groups[index].descriptors, entry)
				break
			}
		}
	}

	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by contractprojection; DO NOT EDIT.\n")
	buffer.WriteString("// Source: server/internal/contract/projection.Targets.\n\n")
	for _, group := range groups {
		if len(group.descriptors) == 0 {
			continue
		}
		_, _ = fmt.Fprintf(&buffer, "export const %s = {\n", group.constant)
		for _, entry := range group.descriptors {
			value, _ := contractValue(entry.Value)
			_, _ = fmt.Fprintf(&buffer, "  %s: %s,\n", entry.Name, typeScriptString(value))
		}
		buffer.WriteString("} as const;\n\n")
		typeAlias := fmt.Sprintf("export type %s = (typeof %s)[keyof typeof %s];", group.typeName, group.constant, group.constant)
		if len(typeAlias) > maxInlineTypeAliasLength {
			_, _ = fmt.Fprintf(&buffer, "export type %s =\n  (typeof %s)[keyof typeof %s];\n\n", group.typeName, group.constant, group.constant)
			continue
		}
		buffer.WriteString(typeAlias + "\n\n")
	}
	return []byte(strings.TrimRight(buffer.String(), "\n") + "\n"), nil
}

func typeScriptString(value string) string {
	escaped := strings.ReplaceAll(value, "\\", "\\\\")
	escaped = strings.ReplaceAll(escaped, "'", "\\'")
	escaped = strings.ReplaceAll(escaped, "\n", "\\n")
	escaped = strings.ReplaceAll(escaped, "\r", "\\r")
	return "'" + escaped + "'"
}
