CREATE TABLE build_builder_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id VARCHAR(64) NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  driver_ref VARCHAR(255) NOT NULL,
  driver_version VARCHAR(64) NOT NULL,
  policy_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by BIGINT NULL,
  updated_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NULL,
  CONSTRAINT build_builder_profiles_deleted_at_check CHECK (deleted_at >= 0)
);

CREATE TABLE build_builder_instances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instance_id VARCHAR(64) NOT NULL,
  profile_id BIGINT NOT NULL REFERENCES build_builder_profiles (id) ON DELETE RESTRICT,
  runtime_target_id BIGINT NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  labels_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by BIGINT NULL,
  updated_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NULL,
  CONSTRAINT build_builder_instances_status_check CHECK (status IN ('pending', 'ready', 'draining', 'unavailable')),
  CONSTRAINT build_builder_instances_deleted_at_check CHECK (deleted_at >= 0)
);

CREATE TABLE build_builder_pools (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pool_id VARCHAR(64) NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  scheduling_policy VARCHAR(64) NOT NULL DEFAULT 'round_robin',
  selector_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by BIGINT NULL,
  updated_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NULL,
  CONSTRAINT build_builder_pools_policy_check CHECK (scheduling_policy IN ('round_robin', 'least_load', 'labels', 'affinity', 'region')),
  CONSTRAINT build_builder_pools_deleted_at_check CHECK (deleted_at >= 0)
);

CREATE UNIQUE INDEX uq_build_builder_profiles_live_id ON build_builder_profiles (profile_id) WHERE deleted_at = 0;
CREATE UNIQUE INDEX uq_build_builder_instances_live_id ON build_builder_instances (instance_id) WHERE deleted_at = 0;
CREATE UNIQUE INDEX uq_build_builder_pools_live_id ON build_builder_pools (pool_id) WHERE deleted_at = 0;
CREATE INDEX idx_build_builder_instances_profile_live ON build_builder_instances (profile_id, status) WHERE deleted_at = 0;
CREATE INDEX idx_build_builder_instances_target_live ON build_builder_instances (runtime_target_id, status) WHERE deleted_at = 0;

