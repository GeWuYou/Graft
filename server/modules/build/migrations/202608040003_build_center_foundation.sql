CREATE TABLE build_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  build_id VARCHAR(32) NOT NULL,
  task_id BIGINT NOT NULL,
  application_id BIGINT NOT NULL,
  application_name_snapshot VARCHAR(255) NOT NULL,
  workspace_context_path TEXT NOT NULL,
  dockerfile_path TEXT NOT NULL,
  runtime_target_id BIGINT NOT NULL,
  runtime_provider VARCHAR(64) NOT NULL,
  executor_kind VARCHAR(64) NOT NULL,
  image_repository VARCHAR(255) NOT NULL,
  image_tag VARCHAR(255) NOT NULL,
  created_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_build_jobs_build_id UNIQUE (build_id),
  CONSTRAINT uq_build_jobs_task_id UNIQUE (task_id),
  CONSTRAINT build_jobs_task_id_fkey FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE RESTRICT
);

CREATE INDEX idx_build_jobs_application_created ON build_jobs (application_id, created_at DESC, id DESC);
CREATE INDEX idx_build_jobs_image_reference ON build_jobs (image_repository, image_tag);

CREATE TABLE build_job_args (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  build_job_id BIGINT NOT NULL,
  name VARCHAR(128) NOT NULL,
  value TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT build_job_args_job_fkey FOREIGN KEY (build_job_id) REFERENCES build_jobs (id) ON DELETE RESTRICT,
  CONSTRAINT uq_build_job_args_name UNIQUE (build_job_id, name)
);

CREATE TABLE build_artifacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artifact_id VARCHAR(32) NOT NULL,
  build_job_id BIGINT NOT NULL,
  role VARCHAR(32) NOT NULL,
  artifact_type VARCHAR(64) NOT NULL,
  media_type VARCHAR(255) NOT NULL,
  runtime_provider VARCHAR(64) NOT NULL,
  runtime_target_id BIGINT NOT NULL,
  image_id VARCHAR(255) NOT NULL,
  digest VARCHAR(255) NOT NULL,
  repository VARCHAR(255) NOT NULL,
  tag VARCHAR(255) NOT NULL,
  size_bytes BIGINT NOT NULL,
  os VARCHAR(32) NOT NULL,
  architecture VARCHAR(32) NOT NULL,
  variant VARCHAR(32) NOT NULL DEFAULT '',
  producer_version VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_build_artifacts_artifact_id UNIQUE (artifact_id),
  CONSTRAINT build_artifacts_job_fkey FOREIGN KEY (build_job_id) REFERENCES build_jobs (id) ON DELETE RESTRICT,
  CONSTRAINT uq_build_artifacts_primary UNIQUE (build_job_id, role),
  CONSTRAINT build_artifacts_size_check CHECK (size_bytes >= 0)
);

CREATE INDEX idx_build_artifacts_reference ON build_artifacts (repository, tag);
CREATE INDEX idx_build_artifacts_target ON build_artifacts (runtime_target_id, created_at DESC);

