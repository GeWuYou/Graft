CREATE TABLE build_platform_artifacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execution_plan_id BIGINT NOT NULL REFERENCES build_execution_plans (id) ON DELETE RESTRICT,
  leg_id VARCHAR(128) NOT NULL,
  artifact_id BIGINT NOT NULL REFERENCES build_v2_artifacts (id) ON DELETE RESTRICT,
  platform VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_build_platform_artifacts_plan_leg UNIQUE (execution_plan_id, leg_id),
  CONSTRAINT uq_build_platform_artifacts_plan_platform UNIQUE (execution_plan_id, platform)
);

CREATE INDEX idx_build_platform_artifacts_artifact_created ON build_platform_artifacts (artifact_id, created_at DESC);

COMMENT ON TABLE build_platform_artifacts IS '协调构建中每个平台生成的不可变产物映射';
COMMENT ON COLUMN build_platform_artifacts.id IS '平台构建产物映射内部主键';
COMMENT ON COLUMN build_platform_artifacts.execution_plan_id IS '所属不可变执行计划内部标识';
COMMENT ON COLUMN build_platform_artifacts.leg_id IS 'Task Runtime 协调执行腿稳定标识';
COMMENT ON COLUMN build_platform_artifacts.artifact_id IS '对应摘要寻址不可变产物内部标识';
COMMENT ON COLUMN build_platform_artifacts.platform IS '产物目标操作系统与处理器平台标识';
COMMENT ON COLUMN build_platform_artifacts.created_at IS '平台产物关联创建时间';
