CREATE TABLE build_workspace_snapshot_access (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_snapshot_id BIGINT NOT NULL REFERENCES build_workspace_snapshots (id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0
);

COMMENT ON TABLE build_workspace_snapshot_access IS '构建输入快照与用户之间的可复用访问关系';
COMMENT ON COLUMN build_workspace_snapshot_access.id IS '快照访问关系主键';
COMMENT ON COLUMN build_workspace_snapshot_access.workspace_snapshot_id IS '关联的构建工作区快照内部标识';
COMMENT ON COLUMN build_workspace_snapshot_access.user_id IS '获得快照复用权限的用户标识';
COMMENT ON COLUMN build_workspace_snapshot_access.created_by IS '创建快照访问关系的操作者标识';
COMMENT ON COLUMN build_workspace_snapshot_access.created_at IS '快照访问关系创建时间';
COMMENT ON COLUMN build_workspace_snapshot_access.deleted_at IS '软删除时间戳，零表示关系有效';
COMMENT ON COLUMN build_workspace_snapshot_access.deleted_by IS '软删除关系的操作者标识，零表示关系有效';

CREATE UNIQUE INDEX uq_build_workspace_snapshot_access_live
  ON build_workspace_snapshot_access (workspace_snapshot_id, user_id)
  WHERE deleted_at = 0;

CREATE INDEX idx_build_workspace_snapshot_access_user_live
  ON build_workspace_snapshot_access (user_id, created_at DESC, id DESC)
  WHERE deleted_at = 0;
