CREATE TABLE build_builder_pool_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pool_id BIGINT NOT NULL REFERENCES build_builder_pools (id) ON DELETE RESTRICT,
  instance_id BIGINT NOT NULL REFERENCES build_builder_instances (id) ON DELETE RESTRICT,
  priority INTEGER NOT NULL DEFAULT 0,
  created_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NULL,
  CONSTRAINT build_builder_pool_members_priority_check CHECK (priority >= 0),
  CONSTRAINT build_builder_pool_members_deleted_at_check CHECK (deleted_at >= 0)
);

CREATE UNIQUE INDEX uq_build_builder_pool_members_live_pair
  ON build_builder_pool_members (pool_id, instance_id) WHERE deleted_at = 0;
CREATE INDEX idx_build_builder_pool_members_live_pool
  ON build_builder_pool_members (pool_id, priority, instance_id) WHERE deleted_at = 0;

COMMENT ON TABLE build_builder_pool_members IS 'Builder Pool 与可调度 Instance 的成员关系';
COMMENT ON COLUMN build_builder_pool_members.id IS 'Pool 成员关系主键';
COMMENT ON COLUMN build_builder_pool_members.pool_id IS '关联的 Builder Pool 内部标识';
COMMENT ON COLUMN build_builder_pool_members.instance_id IS '关联的 Builder Instance 内部标识';
COMMENT ON COLUMN build_builder_pool_members.priority IS '成员在确定性选择中的稳定优先级，数值越小越优先';
COMMENT ON COLUMN build_builder_pool_members.created_by IS '创建成员关系的操作者标识';
COMMENT ON COLUMN build_builder_pool_members.created_at IS '成员关系创建时间';
COMMENT ON COLUMN build_builder_pool_members.deleted_at IS '成员关系软删除时间戳，零表示仍可用';
COMMENT ON COLUMN build_builder_pool_members.deleted_by IS '执行成员关系软删除的操作者标识';
