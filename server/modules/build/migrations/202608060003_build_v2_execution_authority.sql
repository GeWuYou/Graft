CREATE TABLE build_workspace_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id VARCHAR(64) NOT NULL,
  source_kind VARCHAR(64) NOT NULL,
  source_reference VARCHAR(255) NOT NULL,
  content_digest VARCHAR(255) NOT NULL,
  materialization_ref VARCHAR(255) NOT NULL,
  created_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_build_workspace_snapshots_snapshot_id UNIQUE (snapshot_id),
  CONSTRAINT uq_build_workspace_snapshots_digest UNIQUE (content_digest)
);

CREATE TABLE build_execution_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id VARCHAR(64) NOT NULL,
  plan_digest VARCHAR(255) NOT NULL,
  workspace_snapshot_id BIGINT NOT NULL REFERENCES build_workspace_snapshots (id) ON DELETE RESTRICT,
  task_id BIGINT NOT NULL UNIQUE REFERENCES tasks (id) ON DELETE RESTRICT,
  runtime_target_id BIGINT NOT NULL,
  driver VARCHAR(64) NOT NULL,
  template_ref VARCHAR(255) NOT NULL,
  platforms_json JSONB NOT NULL,
  destination_json JSONB NOT NULL,
  created_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_build_execution_plans_plan_id UNIQUE (plan_id),
  CONSTRAINT uq_build_execution_plans_plan_digest UNIQUE (plan_digest)
);

CREATE TABLE build_v2_artifacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artifact_id VARCHAR(64) NOT NULL,
  artifact_digest VARCHAR(255) NOT NULL,
  media_type VARCHAR(255) NOT NULL,
  platforms_json JSONB NOT NULL,
  size_bytes BIGINT NOT NULL,
  produced_plan_id BIGINT NOT NULL REFERENCES build_execution_plans (id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_build_v2_artifacts_artifact_id UNIQUE (artifact_id),
  CONSTRAINT uq_build_v2_artifacts_digest UNIQUE (artifact_digest),
  CONSTRAINT build_v2_artifacts_size_check CHECK (size_bytes >= 0)
);

CREATE TABLE build_publications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publication_id VARCHAR(64) NOT NULL,
  artifact_id BIGINT NOT NULL REFERENCES build_v2_artifacts (id) ON DELETE RESTRICT,
  destination_kind VARCHAR(64) NOT NULL,
  connection_ref VARCHAR(255) NOT NULL,
  repository_ref VARCHAR(255) NOT NULL,
  mutable_reference VARCHAR(255) NOT NULL,
  credential_execution_mode VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_build_publications_publication_id UNIQUE (publication_id),
  CONSTRAINT uq_build_publications_destination_reference UNIQUE (connection_ref, repository_ref, mutable_reference)
);

CREATE INDEX idx_build_execution_plans_snapshot_created ON build_execution_plans (workspace_snapshot_id, created_at DESC);
CREATE INDEX idx_build_v2_artifacts_plan_created ON build_v2_artifacts (produced_plan_id, created_at DESC);
CREATE INDEX idx_build_publications_artifact_created ON build_publications (artifact_id, created_at DESC);

