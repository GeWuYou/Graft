CREATE TABLE build_provider_execution_evidence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execution_plan_id BIGINT NOT NULL REFERENCES build_execution_plans (id) ON DELETE RESTRICT,
  task_id BIGINT NOT NULL REFERENCES tasks (id) ON DELETE RESTRICT,
  stage_id BIGINT NOT NULL,
  runtime_target_id BIGINT NOT NULL,
  platform VARCHAR(128) NOT NULL,
  provider_id VARCHAR(128) NOT NULL,
  conformance_version VARCHAR(64) NOT NULL,
  snapshot_delivery_proof BOOLEAN NOT NULL,
  driver_execution_proof BOOLEAN NOT NULL,
  publication_proof BOOLEAN NOT NULL,
  cancellation_proof BOOLEAN NOT NULL,
  cleanup_proof BOOLEAN NOT NULL,
  observed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_build_provider_execution_evidence_plan_stage UNIQUE (execution_plan_id, stage_id)
);

CREATE INDEX idx_build_provider_execution_evidence_task_observed
  ON build_provider_execution_evidence (task_id, observed_at DESC);

COMMENT ON TABLE build_provider_execution_evidence IS '构建执行前由运行目标提供方确认的非秘密能力证据';
COMMENT ON COLUMN build_provider_execution_evidence.id IS '提供方执行证据内部主键';
COMMENT ON COLUMN build_provider_execution_evidence.execution_plan_id IS '关联不可变执行计划内部标识';
COMMENT ON COLUMN build_provider_execution_evidence.task_id IS '产生证据的 Task Runtime 任务标识';
COMMENT ON COLUMN build_provider_execution_evidence.stage_id IS '产生证据的 Task Runtime 阶段标识';
COMMENT ON COLUMN build_provider_execution_evidence.runtime_target_id IS '完成能力确认的运行目标标识';
COMMENT ON COLUMN build_provider_execution_evidence.platform IS '本次执行确认对应的目标平台';
COMMENT ON COLUMN build_provider_execution_evidence.provider_id IS '运行目标提供方稳定标识';
COMMENT ON COLUMN build_provider_execution_evidence.conformance_version IS '提供方能力证明契约版本';
COMMENT ON COLUMN build_provider_execution_evidence.snapshot_delivery_proof IS '是否确认可交付冻结工作区快照';
COMMENT ON COLUMN build_provider_execution_evidence.driver_execution_proof IS '是否确认可执行冻结构建驱动';
COMMENT ON COLUMN build_provider_execution_evidence.publication_proof IS '是否确认可完成受控产物发布';
COMMENT ON COLUMN build_provider_execution_evidence.cancellation_proof IS '是否确认支持任务取消与恢复约束';
COMMENT ON COLUMN build_provider_execution_evidence.cleanup_proof IS '是否确认支持快照物化清理约束';
COMMENT ON COLUMN build_provider_execution_evidence.observed_at IS '提供方能力证据记录时间';
