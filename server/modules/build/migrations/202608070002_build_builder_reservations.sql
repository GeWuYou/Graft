CREATE TABLE build_builder_reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id VARCHAR(64) NOT NULL,
  builder_instance_id VARCHAR(64) NOT NULL,
  plan_id VARCHAR(64) NOT NULL,
  task_id BIGINT NOT NULL,
  attempt INTEGER NOT NULL DEFAULT 1,
  fence_token VARCHAR(64) NOT NULL,
  state VARCHAR(16) NOT NULL DEFAULT 'reserved',
  lease_expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT build_builder_reservations_state_check CHECK (state IN ('reserved', 'accepted', 'running', 'released', 'expired', 'abandoned')),
  CONSTRAINT build_builder_reservations_fence_not_blank CHECK (btrim(fence_token) <> ''),
  CONSTRAINT build_builder_reservations_task_positive CHECK (task_id > 0),
  CONSTRAINT build_builder_reservations_attempt_positive CHECK (attempt > 0)
);

CREATE UNIQUE INDEX uq_build_builder_reservations_live_instance
  ON build_builder_reservations (builder_instance_id)
  WHERE state IN ('reserved', 'accepted', 'running');
CREATE UNIQUE INDEX uq_build_builder_reservations_reservation_id
  ON build_builder_reservations (reservation_id);
CREATE UNIQUE INDEX uq_build_builder_reservations_plan_task_attempt
  ON build_builder_reservations (plan_id, task_id, attempt);
CREATE INDEX idx_build_builder_reservations_state_updated
  ON build_builder_reservations (state, updated_at);

COMMENT ON TABLE build_builder_reservations IS 'Build 对 Builder Instance 的容量租约与 fencing 事实';
COMMENT ON COLUMN build_builder_reservations.id IS '容量租约内部主键';
COMMENT ON COLUMN build_builder_reservations.reservation_id IS '容量租约公开稳定标识';
COMMENT ON COLUMN build_builder_reservations.builder_instance_id IS '被占用的 Builder Instance 稳定标识';
COMMENT ON COLUMN build_builder_reservations.plan_id IS '冻结该容量选择的 Execution Plan 标识';
COMMENT ON COLUMN build_builder_reservations.task_id IS '消费该容量租约的 Task Runtime 任务标识';
COMMENT ON COLUMN build_builder_reservations.attempt IS 'Task Runtime 当前执行尝试编号，重试必须递增并取得新 fence';
COMMENT ON COLUMN build_builder_reservations.fence_token IS '拒绝旧执行尝试的 attempt-scoped fencing token';
COMMENT ON COLUMN build_builder_reservations.state IS '容量租约状态，终态由 Build 释放或进入人工恢复';
COMMENT ON COLUMN build_builder_reservations.lease_expires_at IS 'reserved 或 accepted 容量租约的自然到期时间；running 不按普通 TTL 回收';
COMMENT ON COLUMN build_builder_reservations.created_at IS '容量租约创建时间';
COMMENT ON COLUMN build_builder_reservations.updated_at IS '容量租约最近变更时间';
