CREATE TABLE build_workspaces (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id VARCHAR(64) NOT NULL,
  display_name VARCHAR(255) NOT NULL,
  source_kind VARCHAR(64) NOT NULL,
  source_reference VARCHAR(255) NOT NULL,
  retention_policy VARCHAR(64) NOT NULL DEFAULT 'workspace',
  created_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_build_workspaces_workspace_id UNIQUE (workspace_id),
  CONSTRAINT build_workspaces_source_kind_check CHECK (source_kind IN ('application_workspace', 'git', 'uploaded_archive', 'generated', 'target_local')),
  CONSTRAINT build_workspaces_deleted_at_check CHECK (deleted_at >= 0)
);

ALTER TABLE build_workspace_snapshots
  ADD COLUMN workspace_id BIGINT NULL REFERENCES build_workspaces (id) ON DELETE RESTRICT;

CREATE INDEX idx_build_workspaces_source_live ON build_workspaces (source_kind, created_at DESC) WHERE deleted_at = 0;
CREATE INDEX idx_build_workspace_snapshots_workspace_created ON build_workspace_snapshots (workspace_id, created_at DESC);

COMMENT ON TABLE build_workspaces IS '构建领域可复用的工作区来源定义';
COMMENT ON COLUMN build_workspaces.id IS '工作区内部主键';
COMMENT ON COLUMN build_workspaces.workspace_id IS '工作区公开稳定标识';
COMMENT ON COLUMN build_workspaces.display_name IS '工作区展示名称';
COMMENT ON COLUMN build_workspaces.source_kind IS '工作区来源类型';
COMMENT ON COLUMN build_workspaces.source_reference IS '来源对象的稳定引用，不包含主机路径或秘密';
COMMENT ON COLUMN build_workspaces.retention_policy IS '工作区及其后续快照的默认保留策略';
COMMENT ON COLUMN build_workspaces.created_by IS '创建工作区的操作者标识';
COMMENT ON COLUMN build_workspaces.created_at IS '工作区创建时间';
COMMENT ON COLUMN build_workspaces.updated_at IS '工作区元数据最后更新时间';
COMMENT ON COLUMN build_workspaces.deleted_at IS '工作区软删除时间戳，零表示仍可用';
COMMENT ON COLUMN build_workspace_snapshots.workspace_id IS '产生该不可变快照的 Build 工作区内部标识';
