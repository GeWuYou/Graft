CREATE TABLE saved_views (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id BIGINT NOT NULL,
  surface_key VARCHAR(120) NOT NULL,
  name VARCHAR(120) NOT NULL,
  query_state_json JSONB NOT NULL,
  page_size INTEGER NOT NULL,
  visible_columns_json JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  created_by BIGINT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  updated_by BIGINT NOT NULL,
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT saved_views_page_size_check CHECK (page_size > 0 AND page_size <= 500),
  CONSTRAINT saved_views_query_state_object_check CHECK (jsonb_typeof(query_state_json) = 'object'),
  CONSTRAINT saved_views_columns_array_check CHECK (jsonb_typeof(visible_columns_json) = 'array')
);

CREATE UNIQUE INDEX uq_saved_views_owner_surface_name_live ON saved_views (owner_user_id, surface_key, name) WHERE deleted_at = 0;
CREATE INDEX idx_saved_views_owner_surface_updated_live ON saved_views (owner_user_id, surface_key, updated_at DESC, id DESC) WHERE deleted_at = 0;

COMMENT ON TABLE saved_views IS '分页列表用户私有保存视图表';
COMMENT ON COLUMN saved_views.id IS '保存视图主键';
COMMENT ON COLUMN saved_views.owner_user_id IS '拥有保存视图的用户标识';
COMMENT ON COLUMN saved_views.surface_key IS '消费该视图的列表页面稳定标识';
COMMENT ON COLUMN saved_views.name IS '同一用户页面范围内唯一的展示名称';
COMMENT ON COLUMN saved_views.query_state_json IS '由消费页面校验的筛选与查询状态 JSON';
COMMENT ON COLUMN saved_views.page_size IS '应用视图时使用的每页记录数';
COMMENT ON COLUMN saved_views.visible_columns_json IS '用户选择显示的列表列稳定键数组';
COMMENT ON COLUMN saved_views.created_at IS '保存视图创建时间';
COMMENT ON COLUMN saved_views.created_by IS '创建保存视图的用户标识';
COMMENT ON COLUMN saved_views.updated_at IS '保存视图最近更新时间';
COMMENT ON COLUMN saved_views.updated_by IS '最后更新保存视图的用户标识';
COMMENT ON COLUMN saved_views.deleted_at IS '软删除时间戳，零表示有效记录';
COMMENT ON COLUMN saved_views.deleted_by IS '执行软删除的用户标识，零表示未删除';
