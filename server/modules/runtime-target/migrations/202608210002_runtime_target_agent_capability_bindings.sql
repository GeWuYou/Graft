-- Docker Runtime Agent 升格：以显式能力集合取代实验期单 profile 的执行准入职责。
CREATE TABLE runtime_target_agent_capability_bindings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identity_id BIGINT NOT NULL REFERENCES runtime_target_agent_identities(id) ON DELETE RESTRICT,
  provider_id VARCHAR(64) NOT NULL,
  capabilities JSONB NOT NULL,
  capability_version VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by BIGINT NOT NULL DEFAULT 0,
  updated_by BIGINT NOT NULL DEFAULT 0,
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_runtime_target_agent_capability_bindings_identity UNIQUE (identity_id),
  CONSTRAINT runtime_target_agent_capability_bindings_provider_check CHECK (trim(provider_id) <> ''),
  CONSTRAINT runtime_target_agent_capability_bindings_capabilities_check CHECK (jsonb_typeof(capabilities) = 'array' AND jsonb_array_length(capabilities) > 0),
  CONSTRAINT runtime_target_agent_capability_bindings_version_check CHECK (trim(capability_version) <> '')
);

COMMENT ON TABLE runtime_target_agent_capability_bindings IS 'Runtime Target Agent 的 provider-neutral 能力绑定事实';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.id IS '能力绑定事实内部主键';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.identity_id IS '关联 Runtime Target Agent 稳定身份主键';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.provider_id IS '能力绑定所属的运行时提供方标识';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.capabilities IS 'Agent 已声明且由 Runtime Target 允许的能力名称数组';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.capability_version IS '能力绑定协议版本';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.created_at IS '能力绑定事实创建时间';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.updated_at IS '能力绑定事实最近更新时间';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.created_by IS '创建能力绑定事实的操作者主键，系统写入为零';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.updated_by IS '最近更新能力绑定事实的操作者主键，系统写入为零';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.deleted_at IS '能力绑定事实软删除时间戳，零表示当前有效';
COMMENT ON COLUMN runtime_target_agent_capability_bindings.deleted_by IS '执行能力绑定事实软删除的操作者主键，零表示未删除';

-- 单窗口迁移只复制一次旧 profile；本迁移生效后 execution admission 只读取新表。
-- 删除触发器：全部活动身份均存在 runtime/v1 binding，且 Builder telemetry 不再读取旧字段后，删除旧 profile 列。
INSERT INTO runtime_target_agent_capability_bindings (identity_id, provider_id, capabilities, capability_version)
SELECT id, provider_id, jsonb_build_array(capability_profile), 'runtime/v1'
FROM runtime_target_agent_identities
WHERE deleted_at = 0
ON CONFLICT (identity_id) DO NOTHING;
