-- 创建运行目标与用户之间的部署授权绑定，版本编号已在默认迁移链中全局去重。
CREATE TABLE runtime_target_user_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  runtime_target_id bigint NOT NULL,
  user_id bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  created_by bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT NOW(),
  updated_by bigint NOT NULL DEFAULT 0,
  deleted_at bigint NOT NULL DEFAULT 0,
  deleted_by bigint NOT NULL DEFAULT 0,
  CONSTRAINT fk_runtime_target_user_assignments_target FOREIGN KEY (runtime_target_id) REFERENCES runtime_targets(id)
);
-- This unique key makes grant/revoke restoration idempotent while retaining soft-delete history.
CREATE UNIQUE INDEX uq_runtime_target_user_assignments_target_user ON runtime_target_user_assignments (runtime_target_id, user_id);
-- Active candidate lookup is bounded by the current user and joins only live target records.
CREATE INDEX idx_runtime_target_user_assignments_live_user ON runtime_target_user_assignments (user_id, runtime_target_id) WHERE deleted_at = 0;
COMMENT ON TABLE runtime_target_user_assignments IS '运行目标部署使用授权关系表';
COMMENT ON COLUMN runtime_target_user_assignments.id IS '部署使用授权记录主键';
COMMENT ON COLUMN runtime_target_user_assignments.runtime_target_id IS '关联的运行目标主键';
COMMENT ON COLUMN runtime_target_user_assignments.user_id IS '被授予部署使用权的用户标识';
COMMENT ON COLUMN runtime_target_user_assignments.created_at IS '授权创建时间';
COMMENT ON COLUMN runtime_target_user_assignments.created_by IS '创建授权的操作者标识';
COMMENT ON COLUMN runtime_target_user_assignments.updated_at IS '授权最近更新时间';
COMMENT ON COLUMN runtime_target_user_assignments.updated_by IS '最后更新授权的操作者标识';
COMMENT ON COLUMN runtime_target_user_assignments.deleted_at IS '软删除时间戳，零表示授权有效';
COMMENT ON COLUMN runtime_target_user_assignments.deleted_by IS '撤销授权的操作者标识，零表示未撤销';
