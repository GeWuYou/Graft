CREATE TABLE runtime_target_agent_ledger_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  generation_id BIGINT NOT NULL REFERENCES runtime_target_agent_generations(id) ON DELETE RESTRICT,
  snapshot_id CHAR(64) NOT NULL,
  snapshot_digest CHAR(64) NOT NULL,
  sequence BIGINT NOT NULL,
  builder_scope VARCHAR(512) NOT NULL,
  provider_id VARCHAR(64) NOT NULL,
  capability_profile VARCHAR(255) NOT NULL,
  capability_version VARCHAR(255) NOT NULL,
  affinity_key VARCHAR(512) NOT NULL,
  available BOOLEAN NOT NULL,
  running INTEGER NOT NULL,
  queued INTEGER NOT NULL,
  allocatable_slots INTEGER NOT NULL,
  observed_at TIMESTAMPTZ NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  issued_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  receipt_fingerprint CHAR(64) NOT NULL DEFAULT '',
  receipt_observed_at TIMESTAMPTZ,
  receipt_expires_at TIMESTAMPTZ,
  receipt_available BOOLEAN,
  receipt_implementation_version VARCHAR(255) NOT NULL DEFAULT '',
  receipt_diagnostic VARCHAR(1024) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by BIGINT NOT NULL DEFAULT 0,
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_runtime_target_agent_ledger_snapshots_id UNIQUE (snapshot_id),
  CONSTRAINT uq_runtime_target_agent_ledger_snapshots_generation_sequence UNIQUE (generation_id, sequence),
  CONSTRAINT runtime_target_agent_ledger_snapshots_id_check CHECK (snapshot_id ~ '^[0-9a-f]{64}$'),
  CONSTRAINT runtime_target_agent_ledger_snapshots_digest_check CHECK (snapshot_digest ~ '^[0-9a-f]{64}$'),
  CONSTRAINT runtime_target_agent_ledger_snapshots_sequence_check CHECK (sequence > 0),
  CONSTRAINT runtime_target_agent_ledger_snapshots_capacity_check CHECK (running >= 0 AND queued >= 0 AND allocatable_slots >= 0),
  CONSTRAINT runtime_target_agent_ledger_snapshots_expiry_check CHECK (expires_at > issued_at),
  CONSTRAINT runtime_target_agent_ledger_snapshots_receipt_check CHECK ((consumed_at IS NULL AND receipt_fingerprint = '') OR (consumed_at IS NOT NULL AND receipt_fingerprint ~ '^[0-9a-f]{64}$' AND receipt_observed_at IS NOT NULL AND receipt_expires_at IS NOT NULL AND receipt_available IS NOT NULL))
);

CREATE INDEX idx_runtime_target_agent_ledger_snapshots_live_expiry
  ON runtime_target_agent_ledger_snapshots (generation_id, expires_at)
  WHERE deleted_at = 0;

