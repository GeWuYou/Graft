CREATE TABLE runtime_target_agent_generations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identity_id BIGINT NOT NULL REFERENCES runtime_target_agent_identities(id) ON DELETE RESTRICT,
  generation BIGINT NOT NULL,
  enrollment_ref VARCHAR(512) NOT NULL,
  trust_bundle_ref VARCHAR(512) NOT NULL,
  trust_bundle_version VARCHAR(255) NOT NULL,
  certificate_issuer VARCHAR(512) NOT NULL DEFAULT '',
  certificate_serial VARCHAR(512) NOT NULL DEFAULT '',
  public_key_fingerprint VARCHAR(512) NOT NULL DEFAULT '',
  expires_at TIMESTAMPTZ NOT NULL,
  status VARCHAR(32) NOT NULL,
  activated_at TIMESTAMPTZ,
  retired_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  revoked_reason VARCHAR(512) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by BIGINT NOT NULL DEFAULT 0,
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_runtime_target_agent_generations_identity_generation UNIQUE (identity_id, generation),
  CONSTRAINT runtime_target_agent_generations_positive_generation_check CHECK (generation > 0),
  CONSTRAINT runtime_target_agent_generations_status_check CHECK (status IN ('pending', 'active', 'revoked', 'retired')),
  CONSTRAINT runtime_target_agent_generations_pending_metadata_check CHECK (
    status <> 'pending' OR (certificate_serial = '' AND public_key_fingerprint = '' AND activated_at IS NULL)
  ),
  CONSTRAINT runtime_target_agent_generations_active_metadata_check CHECK (
    status <> 'active' OR (certificate_issuer <> '' AND certificate_serial <> '' AND public_key_fingerprint <> '' AND activated_at IS NOT NULL AND revoked_at IS NULL AND retired_at IS NULL)
  ),
  CONSTRAINT runtime_target_agent_generations_revoked_timestamp_check CHECK (status <> 'revoked' OR revoked_at IS NOT NULL),
  CONSTRAINT runtime_target_agent_generations_retired_timestamp_check CHECK (status <> 'retired' OR retired_at IS NOT NULL)
);

CREATE UNIQUE INDEX uq_runtime_target_agent_generations_active_identity
  ON runtime_target_agent_generations (identity_id)
  WHERE status = 'active' AND deleted_at = 0;

CREATE INDEX idx_runtime_target_agent_generations_active_lookup
  ON runtime_target_agent_generations (identity_id, generation, expires_at)
  WHERE status = 'active' AND deleted_at = 0;

