CREATE TABLE runtime_target_agent_identities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  runtime_target_id BIGINT NOT NULL REFERENCES runtime_targets(id) ON DELETE RESTRICT,
  identity_id VARCHAR(255) NOT NULL,
  agent_id VARCHAR(255) NOT NULL,
  provider_id VARCHAR(128) NOT NULL,
  builder_scope VARCHAR(255) NOT NULL,
  capability_profile VARCHAR(255) NOT NULL,
  capability_version VARCHAR(128) NOT NULL,
  image_digest VARCHAR(512) NOT NULL DEFAULT '',
  agent_version VARCHAR(128) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by BIGINT NOT NULL DEFAULT 0,
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT runtime_target_agent_identities_identity_id_check CHECK (btrim(identity_id) <> ''),
  CONSTRAINT runtime_target_agent_identities_agent_id_check CHECK (btrim(agent_id) <> ''),
  CONSTRAINT runtime_target_agent_identities_provider_id_check CHECK (btrim(provider_id) <> ''),
  CONSTRAINT runtime_target_agent_identities_builder_scope_check CHECK (btrim(builder_scope) <> ''),
  CONSTRAINT runtime_target_agent_identities_capability_profile_check CHECK (btrim(capability_profile) <> ''),
  CONSTRAINT runtime_target_agent_identities_capability_version_check CHECK (btrim(capability_version) <> '')
);

CREATE UNIQUE INDEX uq_runtime_target_agent_identities_identity_live
  ON runtime_target_agent_identities (identity_id)
  WHERE deleted_at = 0;

CREATE UNIQUE INDEX uq_runtime_target_agent_identities_target_agent_live
  ON runtime_target_agent_identities (runtime_target_id, agent_id)
  WHERE deleted_at = 0;

