COMMENT ON COLUMN runtime_target_agent_certificate_issuances.issuance_key IS '用于 Vault 幂等查询和重启恢复的稳定签发键';
COMMENT ON COLUMN runtime_target_agent_certificate_issuances.csr_public_key_fingerprint IS '经验证 CSR 公钥的 SHA-256 十六进制指纹';
COMMENT ON COLUMN runtime_target_agent_certificate_issuances.status IS '签发协调状态，取值为 authorized、issued 或 completed';
COMMENT ON COLUMN runtime_target_agent_certificate_issuances.certificate_issuer IS 'Vault 返回的客户端证书签发者非秘密标识';
