CREATE TABLE runtime_target_agent_certificate_issuances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_grant_id BIGINT NOT NULL REFERENCES runtime_target_agent_delivery_grants(id) ON DELETE RESTRICT,
  issuance_key VARCHAR(128) NOT NULL,
  csr_public_key_fingerprint CHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL,
  certificate_issuer VARCHAR(512) NOT NULL DEFAULT '',
  certificate_serial VARCHAR(512) NOT NULL DEFAULT '',
  certificate_public_key_fingerprint VARCHAR(512) NOT NULL DEFAULT '',
  certificate_expires_at TIMESTAMPTZ,
  trust_bundle_ref VARCHAR(512) NOT NULL DEFAULT '',
  trust_bundle_version VARCHAR(255) NOT NULL DEFAULT '',
  trust_bundle_expires_at TIMESTAMPTZ,
  authorized_at TIMESTAMPTZ NOT NULL,
  issued_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by BIGINT NOT NULL DEFAULT 0,
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_runtime_target_agent_certificate_issuances_grant UNIQUE (delivery_grant_id),
  CONSTRAINT uq_runtime_target_agent_certificate_issuances_key UNIQUE (issuance_key),
  CONSTRAINT runtime_target_agent_certificate_issuances_key_check CHECK (btrim(issuance_key) <> ''),
  CONSTRAINT runtime_target_agent_certificate_issuances_csr_fingerprint_check CHECK (csr_public_key_fingerprint ~ '^[0-9a-f]{64}$'),
  CONSTRAINT runtime_target_agent_certificate_issuances_status_check CHECK (status IN ('authorized', 'issued', 'completed')),
  CONSTRAINT runtime_target_agent_certificate_issuances_issued_check CHECK (
    status NOT IN ('issued', 'completed') OR (
      certificate_issuer <> '' AND certificate_serial <> '' AND certificate_public_key_fingerprint <> ''
      AND certificate_expires_at IS NOT NULL AND trust_bundle_ref <> '' AND trust_bundle_version <> ''
      AND trust_bundle_expires_at IS NOT NULL AND issued_at IS NOT NULL
    )
  ),
  CONSTRAINT runtime_target_agent_certificate_issuances_completed_check CHECK (status <> 'completed' OR completed_at IS NOT NULL)
);

CREATE INDEX idx_runtime_target_agent_certificate_issuances_recovery
  ON runtime_target_agent_certificate_issuances (status, authorized_at)
  WHERE deleted_at = 0;

