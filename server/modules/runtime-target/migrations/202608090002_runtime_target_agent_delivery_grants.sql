COMMENT ON COLUMN runtime_target_agent_delivery_grants.deleted_by IS '执行投递授权软删除的操作人主键，零表示未删除';

CREATE TABLE runtime_target_agent_delivery_receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_grant_id BIGINT NOT NULL REFERENCES runtime_target_agent_delivery_grants(id) ON DELETE RESTRICT,
  receipt_id VARCHAR(128) NOT NULL,
  protocol_version VARCHAR(64) NOT NULL,
  automation_id VARCHAR(255) NOT NULL,
  handoff_id VARCHAR(128) NOT NULL,
  asserted_delivered_at TIMESTAMPTZ NOT NULL,
  accepted_at TIMESTAMPTZ NOT NULL,
  docker_installation_ref VARCHAR(512) NOT NULL,
  docker_secret_ref VARCHAR(512) NOT NULL,
  payload_fingerprint CHAR(64) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by BIGINT NOT NULL DEFAULT 0,
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_runtime_target_agent_delivery_receipts_receipt_id UNIQUE (receipt_id),
  CONSTRAINT runtime_target_agent_delivery_receipts_receipt_id_check CHECK (btrim(receipt_id) <> ''),
  CONSTRAINT runtime_target_agent_delivery_receipts_protocol_check CHECK (protocol_version = 'graft.delivery-receipt.v1'),
  CONSTRAINT runtime_target_agent_delivery_receipts_automation_check CHECK (btrim(automation_id) <> ''),
  CONSTRAINT runtime_target_agent_delivery_receipts_handoff_check CHECK (btrim(handoff_id) <> ''),
  CONSTRAINT runtime_target_agent_delivery_receipts_installation_check CHECK (btrim(docker_installation_ref) <> ''),
  CONSTRAINT runtime_target_agent_delivery_receipts_secret_check CHECK (btrim(docker_secret_ref) <> ''),
  CONSTRAINT runtime_target_agent_delivery_receipts_fingerprint_check CHECK (payload_fingerprint ~ '^[0-9a-f]{64}$')
);

-- 每个投递授权只有一份可见回执；相同 receipt_id 的重试由内容摘要比对实现幂等。
CREATE UNIQUE INDEX uq_runtime_target_agent_delivery_receipts_live_grant
  ON runtime_target_agent_delivery_receipts (delivery_grant_id)
  WHERE deleted_at = 0;

CREATE INDEX idx_runtime_target_agent_delivery_receipts_handoff
  ON runtime_target_agent_delivery_receipts (handoff_id)
  WHERE deleted_at = 0;

