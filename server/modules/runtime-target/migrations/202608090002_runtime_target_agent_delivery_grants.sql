CREATE TABLE runtime_target_agent_delivery_grants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  generation_id BIGINT NOT NULL REFERENCES runtime_target_agent_generations(id) ON DELETE RESTRICT,
  grant_id VARCHAR(128) NOT NULL,
  token_verifier CHAR(64) NOT NULL,
  expected_automation_id VARCHAR(255) NOT NULL,
  docker_installation_ref VARCHAR(512) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  status VARCHAR(32) NOT NULL,
  handoff_id VARCHAR(128) NOT NULL DEFAULT '',
  handed_off_at TIMESTAMPTZ,
  delivered_at TIMESTAMPTZ,
  consumed_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  revoked_reason VARCHAR(512) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by BIGINT NOT NULL DEFAULT 0,
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_runtime_target_agent_delivery_grants_grant_id UNIQUE (grant_id),
  CONSTRAINT runtime_target_agent_delivery_grants_grant_id_check CHECK (btrim(grant_id) <> ''),
  CONSTRAINT runtime_target_agent_delivery_grants_token_verifier_check CHECK (token_verifier ~ '^[0-9a-f]{64}$'),
  CONSTRAINT runtime_target_agent_delivery_grants_automation_check CHECK (btrim(expected_automation_id) <> ''),
  CONSTRAINT runtime_target_agent_delivery_grants_installation_check CHECK (btrim(docker_installation_ref) <> ''),
  CONSTRAINT runtime_target_agent_delivery_grants_status_check CHECK (status IN ('pending', 'delivered', 'consumed', 'revoked')),
  CONSTRAINT runtime_target_agent_delivery_grants_handoff_check CHECK (
    (handoff_id = '' AND handed_off_at IS NULL) OR (handoff_id <> '' AND handed_off_at IS NOT NULL)
  ),
  CONSTRAINT runtime_target_agent_delivery_grants_delivered_check CHECK (status NOT IN ('delivered', 'consumed') OR delivered_at IS NOT NULL),
  CONSTRAINT runtime_target_agent_delivery_grants_consumed_check CHECK (status <> 'consumed' OR consumed_at IS NOT NULL),
  CONSTRAINT runtime_target_agent_delivery_grants_revoked_check CHECK (status <> 'revoked' OR revoked_at IS NOT NULL)
);

-- 同一世代同一时刻只允许一个仍可消费的投递授权，保留已撤销授权供审计与重放拒绝使用。
CREATE UNIQUE INDEX uq_runtime_target_agent_delivery_grants_live_generation
  ON runtime_target_agent_delivery_grants (generation_id)
  WHERE status IN ('pending', 'delivered') AND deleted_at = 0;

-- handoff 标识由 Runtime Target 一次性签发，必须跨所有有效历史记录保持唯一。
CREATE UNIQUE INDEX uq_runtime_target_agent_delivery_grants_handoff
  ON runtime_target_agent_delivery_grants (handoff_id)
  WHERE handoff_id <> '' AND deleted_at = 0;

CREATE INDEX idx_runtime_target_agent_delivery_grants_pending_expiry
  ON runtime_target_agent_delivery_grants (status, expires_at)
  WHERE deleted_at = 0;

