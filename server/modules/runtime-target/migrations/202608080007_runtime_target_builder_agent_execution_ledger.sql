CREATE TABLE runtime_target_builder_execution_ledgers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  runtime_target_id BIGINT NOT NULL REFERENCES runtime_targets(id) ON DELETE RESTRICT,
  agent_id VARCHAR(255) NOT NULL,
  slot_budget INTEGER NOT NULL CHECK (slot_budget > 0),
  queued_builds INTEGER NOT NULL DEFAULT 0 CHECK (queued_builds >= 0),
  running_builds INTEGER NOT NULL DEFAULT 0 CHECK (running_builds >= 0),
  telemetry_sequence BIGINT NOT NULL DEFAULT 0 CHECK (telemetry_sequence >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_runtime_target_builder_execution_ledgers_target_agent UNIQUE (runtime_target_id, agent_id),
  CONSTRAINT runtime_target_builder_execution_ledgers_capacity_check CHECK (running_builds <= slot_budget)
);

COMMENT ON TABLE runtime_target_builder_execution_ledgers IS '运行目标持有的构建代理 durable 执行账本';
COMMENT ON COLUMN runtime_target_builder_execution_ledgers.id IS '构建代理执行账本内部主键';
COMMENT ON COLUMN runtime_target_builder_execution_ledgers.runtime_target_id IS '构建代理绑定的运行目标主键';
COMMENT ON COLUMN runtime_target_builder_execution_ledgers.agent_id IS '构建代理稳定身份标识';
COMMENT ON COLUMN runtime_target_builder_execution_ledgers.slot_budget IS '构建代理允许并发运行的最大执行槽位';
COMMENT ON COLUMN runtime_target_builder_execution_ledgers.queued_builds IS '构建代理当前排队构建数量';
COMMENT ON COLUMN runtime_target_builder_execution_ledgers.running_builds IS '构建代理当前运行构建数量';
COMMENT ON COLUMN runtime_target_builder_execution_ledgers.telemetry_sequence IS '该账本已生成的单调遥测序列';
COMMENT ON COLUMN runtime_target_builder_execution_ledgers.created_at IS '执行账本创建时间';
COMMENT ON COLUMN runtime_target_builder_execution_ledgers.updated_at IS '执行账本最近更新时间';
