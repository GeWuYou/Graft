CREATE TABLE platform_network_diagnostic_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_id VARCHAR(128) NOT NULL,
  connected BOOLEAN NOT NULL,
  latency_ms BIGINT NOT NULL,
  http_status INTEGER,
  error_message VARCHAR(512),
  tested_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT platform_network_diagnostic_history_latency_check CHECK (latency_ms >= 0),
  CONSTRAINT platform_network_diagnostic_history_http_status_check CHECK (http_status IS NULL OR (http_status >= 100 AND http_status <= 599))
);

CREATE INDEX idx_platform_network_diagnostic_history_target_tested
  ON platform_network_diagnostic_history (target_id, tested_at DESC, id DESC);

COMMENT ON TABLE platform_network_diagnostic_history IS '平台出站网络固定诊断目标的净化结果历史表';
COMMENT ON COLUMN platform_network_diagnostic_history.id IS '诊断历史记录主键';
COMMENT ON COLUMN platform_network_diagnostic_history.target_id IS '模块注册的固定诊断目标稳定标识';
COMMENT ON COLUMN platform_network_diagnostic_history.connected IS '本次诊断是否确认获得成功的 HTTP 响应';
COMMENT ON COLUMN platform_network_diagnostic_history.latency_ms IS '本次诊断请求完成前测得的延迟毫秒数';
COMMENT ON COLUMN platform_network_diagnostic_history.http_status IS '收到 HTTP 响应时的状态码，未收到响应时为空';
COMMENT ON COLUMN platform_network_diagnostic_history.error_message IS '不含地址凭据或响应体的净化失败摘要';
COMMENT ON COLUMN platform_network_diagnostic_history.tested_at IS '诊断执行完成的 UTC 时间';
