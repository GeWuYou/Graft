CREATE TABLE platform_connectivity_custom_targets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_id VARCHAR(128) NOT NULL,
  display_name VARCHAR(128) NOT NULL,
  endpoint VARCHAR(2048) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by BIGINT NOT NULL DEFAULT 0,
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0
);
COMMENT ON TABLE platform_connectivity_custom_targets IS '平台管理员定义的受安全校验保护的连通性自定义目标表';
COMMENT ON COLUMN platform_connectivity_custom_targets.id IS '自定义目标主键';
COMMENT ON COLUMN platform_connectivity_custom_targets.target_id IS '供连通性注册表和检查记录关联的稳定目标标识';
COMMENT ON COLUMN platform_connectivity_custom_targets.display_name IS '管理员可识别的自定义目标显示名称';
COMMENT ON COLUMN platform_connectivity_custom_targets.endpoint IS '通过 SSRF 校验后的 HTTP 或 HTTPS 目标地址';
COMMENT ON COLUMN platform_connectivity_custom_targets.enabled IS '是否允许批量和单目标连通性检查执行该目标';
COMMENT ON COLUMN platform_connectivity_custom_targets.created_at IS '记录创建时间';
COMMENT ON COLUMN platform_connectivity_custom_targets.created_by IS '创建记录的操作人标识';
COMMENT ON COLUMN platform_connectivity_custom_targets.updated_at IS '最近更新时间';
COMMENT ON COLUMN platform_connectivity_custom_targets.updated_by IS '最近更新操作人标识';
COMMENT ON COLUMN platform_connectivity_custom_targets.deleted_at IS '软删除时间戳，零值表示有效记录';
COMMENT ON COLUMN platform_connectivity_custom_targets.deleted_by IS '执行软删除的操作人标识';
CREATE UNIQUE INDEX platform_connectivity_custom_targets_live_target_id_unique ON platform_connectivity_custom_targets (target_id) WHERE deleted_at = 0;

CREATE TABLE platform_connectivity_checks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_id VARCHAR(128) NOT NULL,
  status VARCHAR(16) NOT NULL,
  latency_ms BIGINT NOT NULL,
  checked_at TIMESTAMPTZ NOT NULL
);
COMMENT ON TABLE platform_connectivity_checks IS '平台连通性检查的可查询净化摘要表';
COMMENT ON COLUMN platform_connectivity_checks.id IS '连通性检查主键';
COMMENT ON COLUMN platform_connectivity_checks.target_id IS '被检查的稳定连通性目标标识';
COMMENT ON COLUMN platform_connectivity_checks.status IS '检查总体状态：healthy、degraded 或 failed';
COMMENT ON COLUMN platform_connectivity_checks.latency_ms IS '检查总耗时的毫秒值';
COMMENT ON COLUMN platform_connectivity_checks.checked_at IS '检查完成的 UTC 时间';
CREATE INDEX platform_connectivity_checks_target_checked_idx ON platform_connectivity_checks (target_id, checked_at DESC, id DESC);

CREATE TABLE platform_connectivity_reports (
  check_id BIGINT PRIMARY KEY REFERENCES platform_connectivity_checks(id) ON DELETE CASCADE,
  schema_version INTEGER NOT NULL,
  report JSONB NOT NULL
);
COMMENT ON TABLE platform_connectivity_reports IS '连通性检查的版本化净化报告表';
COMMENT ON COLUMN platform_connectivity_reports.check_id IS '对应连通性检查的主键';
COMMENT ON COLUMN platform_connectivity_reports.schema_version IS '报告净化结构的版本号';
COMMENT ON COLUMN platform_connectivity_reports.report IS '不含完整出口 IP、凭据和原始网络载荷的结构化报告';
