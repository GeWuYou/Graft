CREATE TABLE credential_vault_issuance_states (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issuance_key VARCHAR(255) NOT NULL,
  certificate_serial VARCHAR(512) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by BIGINT NOT NULL DEFAULT 0,
  deleted_at BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_credential_vault_issuance_states_key UNIQUE (issuance_key),
  CONSTRAINT credential_vault_issuance_states_key_check CHECK (btrim(issuance_key) <> ''),
  CONSTRAINT credential_vault_issuance_states_serial_check CHECK (btrim(certificate_serial) <> '')
);

COMMENT ON TABLE credential_vault_issuance_states IS 'Credential Vault 证书签发的可重启恢复非秘密状态';
COMMENT ON COLUMN credential_vault_issuance_states.id IS '证书签发状态内部主键';
COMMENT ON COLUMN credential_vault_issuance_states.issuance_key IS '跨重启保持稳定的 Vault PKI 签发幂等键';
COMMENT ON COLUMN credential_vault_issuance_states.certificate_serial IS 'Vault 返回的证书序列号，不保存证书 PEM 或私钥';
COMMENT ON COLUMN credential_vault_issuance_states.created_at IS '签发状态创建时间';
COMMENT ON COLUMN credential_vault_issuance_states.created_by IS '创建签发状态的操作人主键，系统操作为零';
COMMENT ON COLUMN credential_vault_issuance_states.updated_at IS '签发状态最近更新时间';
COMMENT ON COLUMN credential_vault_issuance_states.updated_by IS '最近更新签发状态的操作人主键，系统操作为零';
COMMENT ON COLUMN credential_vault_issuance_states.deleted_at IS '签发状态软删除时间戳，零表示保留恢复证据';
COMMENT ON COLUMN credential_vault_issuance_states.deleted_by IS '执行签发状态软删除的操作人主键，零表示未删除';
